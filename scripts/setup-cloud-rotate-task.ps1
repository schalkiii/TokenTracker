# Registers the Windows scheduled task that runs
# scripts/cloud-device-rotate.cjs every hour (hidden window), for accounts on
# the free cloud tier that rotate a single machine slot between two computers.
#
# Usage (from a PowerShell with admin rights, per machine):
#   powershell -File scripts\setup-cloud-rotate-task.ps1 [-StartHour 9]
#
# -StartHour sets the anchor hour of the first daily repetition. Stagger the
# two machines (e.g. 9 on one, 21 on the other) so their rotations rarely
# collide; a collision is harmless — the loser retries on the next hour tick.
#
# What gets registered:
#   Task name: TokenTrackerCloudRotate
#   Trigger:   once at today 0:00+StartHour, then hourly for ~10 years
#   Settings:  StartWhenAvailable (missed runs fire after boot/sleep),
#              40-minute execution cap, never run two instances at once
#   Action:    wscript.exe <repo>\scripts\cloud-device-rotate-hidden.vbs
#
# The task survives reboots and needs no elevation at run time (it runs as the
# current user, like the dashboard autostart itself).

param(
  [int]$StartHour = 9,
  [string]$TaskName = "TokenTrackerCloudRotate"
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$scriptPath = Join-Path $repoRoot "scripts\cloud-device-rotate.cjs"
if (-not (Test-Path $scriptPath)) {
  throw "missing $scriptPath — run this installer from a repo checkout"
}

# Path to node.exe is resolved at registration time because the hidden VBS
# launcher relies on PATH, which scheduled tasks do not inherit reliably.
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) {
  $node = "C:\Program Files\nodejs\node.exe"
  if (-not (Test-Path $node)) { throw "node.exe not found" }
}

# Bake the resolved node path into the per-user hidden launcher next to the
# VBS so the VBS stays portable across machines.
$launcherCmd = Join-Path $env:USERPROFILE ".tokentracker\cloud-device-rotate-launch.cmd"
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $launcherCmd) | Out-Null
@"
@echo off
"$node" "$scriptPath"
"@ | Set-Content -Path $launcherCmd -Encoding ASCII

$vbs = Join-Path $env:USERPROFILE ".tokentracker\cloud-device-rotate-hidden.vbs"
@"
' Hidden launcher for TokenTrackerCloudRotate (generated by setup-cloud-rotate-task.ps1)
Option Explicit
Dim sh, rc
Set sh = CreateObject("WScript.Shell")
rc = sh.Run("cmd.exe /c ""$launcherCmd""", 0, True)
WScript.Quit rc
"@ | Set-Content -Path $vbs -Encoding ASCII

$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$vbs`""
$start = (Get-Date).Date.AddHours($StartHour)
$trigger = New-ScheduledTaskTrigger -Once -At $start `
  -RepetitionInterval (New-TimeSpan -Hours 1) `
  -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable `
  -ExecutionTimeLimit (New-TimeSpan -Minutes 40) -MultipleInstances IgnoreNew

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
  -Settings $settings -Description "TokenTracker: hourly cloud device-slot rotation + upload" -Force | Out-Null

$registered = Get-ScheduledTask -TaskName $TaskName
Write-Host ("registered {0}: state={1} hourly from {2:HH:mm}, catch-up={3}" -f `
  $registered.TaskName, $registered.State, $start, $registered.Settings.StartWhenAvailable)
