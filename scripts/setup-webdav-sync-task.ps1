# Registers the Windows scheduled task that runs the TokenTracker WebDAV
# backup/sync every couple of hours (hidden window):
#
#   node <repo>\bin\tracker.js webdav push     # this machine's history → WebDAV
#   node <repo>\bin\tracker.js webdav pull     # other machines' history ← WebDAV
#
# Usage (PowerShell, per machine, after `tokentracker webdav config` was set up):
#   powershell -File scripts\setup-webdav-sync-task.ps1 [-StartHour 10] [-IntervalHours 2]
#
# Traffic notes for metered providers (坚果云 free tier ≈ 1 GB/month upload):
# push skips the upload while the snapshot's row content is unchanged
# (content-hash gate in src/lib/webdav-sync.js), so an idle machine uploads
# nothing and a working machine uploads the (monolithic) snapshot at most once
# per interval. Raise -IntervalHours if the monthly budget gets tight.
#
# What gets registered:
#   Task name: TokenTrackerWebDavSync
#   Trigger:   once at today 0:00+StartHour, then every IntervalHours for ~10 years
#   Settings:  StartWhenAvailable (missed runs fire after boot/sleep),
#              40-minute execution cap, never run two instances at once
#   Action:    wscript.exe %USERPROFILE%\.tokentracker\webdav-sync-hidden.vbs
#
# The task survives reboots and needs no elevation at run time.

param(
  [int]$StartHour = 10,
  [int]$IntervalHours = 2,
  [string]$TaskName = "TokenTrackerWebDavSync"
)

$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$trackerBin = Join-Path $repoRoot "bin\tracker.js"
if (-not (Test-Path $trackerBin)) {
  throw "missing $trackerBin — run this installer from a repo checkout"
}
if (-not (Test-Path (Join-Path $env:USERPROFILE ".tokentracker\webdav.json"))) {
  throw "no WebDAV config found — run: node bin\tracker.js webdav config --url <dav-url> --username <user> --password <app-password> [--encrypt <passphrase>]"
}

# Path to node.exe is resolved at registration time because scheduled tasks
# do not inherit the user's PATH reliably.
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) {
  $node = "C:\Program Files\nodejs\node.exe"
  if (-not (Test-Path $node)) { throw "node.exe not found" }
}

# Both actions run unconditionally (push failure must not block pulling the
# other machines' snapshots). stderr (where the webdav command logs) is
# appended to webdav-sync.log via cmd — a plaintext channel that stays
# readable even where endpoint security encrypts node-written files.
$launcherCmd = Join-Path $env:USERPROFILE ".tokentracker\webdav-sync-launch.cmd"
$logFile = Join-Path $env:USERPROFILE ".tokentracker\webdav-sync.log"
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $launcherCmd) | Out-Null
@"
@echo off
echo [%DATE% %TIME%] webdav sync start >> "$logFile"
"$node" "$trackerBin" webdav push >> "$logFile" 2>&1
"$node" "$trackerBin" webdav pull >> "$logFile" 2>&1
"@ | Set-Content -Path $launcherCmd -Encoding ASCII

$vbs = Join-Path $env:USERPROFILE ".tokentracker\webdav-sync-hidden.vbs"
@"
' Hidden launcher for TokenTrackerWebDavSync (generated by setup-webdav-sync-task.ps1)
Option Explicit
Dim sh, rc
Set sh = CreateObject("WScript.Shell")
rc = sh.Run("cmd.exe /c ""$launcherCmd""", 0, True)
WScript.Quit rc
"@ | Set-Content -Path $vbs -Encoding ASCII

$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "`"$vbs`""
$start = (Get-Date).Date.AddHours($StartHour)
$trigger = New-ScheduledTaskTrigger -Once -At $start `
  -RepetitionInterval (New-TimeSpan -Hours $IntervalHours) `
  -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable `
  -ExecutionTimeLimit (New-TimeSpan -Minutes 40) -MultipleInstances IgnoreNew

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
  -Settings $settings -Description "TokenTracker: WebDAV backup push + cross-machine pull" -Force | Out-Null

$registered = Get-ScheduledTask -TaskName $TaskName
Write-Host ("registered {0}: state={1} every {2}h from {3:HH:mm}, catch-up={4}" -f `
  $registered.TaskName, $registered.State, $IntervalHours, $start, $registered.Settings.StartWhenAvailable)
